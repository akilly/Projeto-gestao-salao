/**
 * Rotina simplificada: consultas mensais preservam o histórico; conjuntos mantêm
 * um único preço; sugestões não movimentam estoque; contas novas ficam em aberto.
 */
import { amount, cents, stockOf } from './domain.js';
import { localDate } from './core.js';
import { recordsForView } from './navigation.js';

/** Identifica o conjunto independentemente da ordem em que os serviços foram marcados. */
const serviceKey = ids => JSON.stringify([...new Set(ids)].sort());

/** Filtra somente a visualização e agrupa valores por conjunto, sem ratear o preço entre procedimentos. */
export function attendanceSummary(state, month = '') {
    const records = typeof month === 'object' ? recordsForView(state, month) : state.records.filter(r => !month || r.date.slice(0, 7) === month)
        .sort((a, b) => b.date.localeCompare(a.date));
    const groups = new Map(), counts = new Map();
    for (const record of records) {
        const ids = [...new Set(record.serviceIds || [record.serviceId])], key = serviceKey(ids);
        const group = groups.get(key) || { key, ids: [...ids].sort(), count: 0, cents: 0 };
        group.count++;
        group.cents += cents(record.total);
        groups.set(key, group);
        for (const id of ids) counts.set(id, (counts.get(id) || 0) + 1);
    }
    const ranked = [...counts].map(([id, count]) => ({ id, count }))
        .sort((a, b) => b.count - a.count || a.id.localeCompare(b.id));
    return {
        records, ranked, procedures: ranked.reduce((sum, r) => sum + r.count, 0),
        total: amount(records.reduce((sum, r) => sum + cents(r.total), 0)),
        combinations: [...groups.values()].map(g => ({ ...g, total: amount(g.cents) }))
            .sort((a, b) => b.total - a.total || b.count - a.count)
    };
}

/** Acompanha a virada do mês apenas quando a pessoa estava vendo o mês corrente. */
export function rollMonth(selected, previousCurrent, current) {
    return selected === previousCurrent ? current : selected;
}

/** Última ficha da mesma cliente e do mesmo conjunto, até a data escolhida. Nunca altera quantidades. */
export function previousConsumption(state, clientId, serviceIds, date = localDate()) {
    if (!clientId || !serviceIds.length) return null;
    const key = serviceKey(serviceIds);
    const record = [...state.records].reverse().sort((a, b) => b.date.localeCompare(a.date))
        .find(r => r.clientId === clientId && r.date <= date && serviceKey(r.serviceIds || [r.serviceId]) === key);
    if (!record) return null;
    const used = new Map();
    for (const m of state.movements.filter(m => m.type === 'consumption' && m.recordId === record.id))
        used.set(m.productId, (used.get(m.productId) || 0) - m.quantity);
    return { recordId: record.id, date: record.date, items: [...used].map(([productId, quantity]) => {
        const product = state.products.find(p => p.id === productId), available = stockOf(state, productId).quantity;
        const measured = Math.round(quantity * 1000) / 1000;
        return { productId, quantity: measured, available, name: product?.name || 'Produto indisponível', unit: product?.unit || '', unavailable: !product || available < measured };
    }) };
}

/**
 * Cria só a conta do mês atual, uma vez, após configurar o início e o valor.
 * Funciona ao abrir/retomar o aplicativo. Não preenche meses passados nem confirma pagamento.
 */
export function ensureSpaceExpense(state, today = localDate()) {
    const month = today.slice(0, 7), settings = state.settings;
    if (!settings.cutoff || settings.cutoff > today || !Number.isFinite(settings.spaceAmount) || !(settings.spaceAmount > 0) ||
        !Number.isInteger(settings.spaceDueDay) || settings.spaceDueDay < 1 || settings.spaceDueDay > 28 ||
        (state.settings.skippedSpaceMonths||[]).includes(month) || state.expenses.some(e => e.recurringMonth === month)) return { state, expense: null };
    const id = `auto-space-${month}`;
    if (state.expenses.some(e => e.id === id)) return { state, expense: null };
    const expense = {
        id, category: 'space', description: `Espaço compartilhado · ${month.slice(5)}/${month.slice(0, 4)}`,
        amount: settings.spaceAmount, date: month + '-01' < settings.cutoff ? settings.cutoff : month + '-01',
        due: `${month}-${String(settings.spaceDueDay).padStart(2, '0')}`, paidDate: null,
        isOpening: false, recurringMonth: month, autoGenerated: true
    };
    const next = structuredClone(state);
    next.expenses.push(expense);
    return { state: next, expense };
}
